// 로비(지도) 화면의 이동 구역.
//
// **좌표는 배경 그림 위의 백분율이다** (왼쪽 위가 0,0 · 오른쪽 아래가 100,100).
// 픽셀이 아니라 백분율이라 화면 크기가 달라져도 그대로 맞는다.
// 그림을 바꾸면 여기 숫자만 고치면 된다 — 화면 코드(`components/Lobby.tsx`)는 건드리지 않는다.
//
// **공용 장소만 올린다.** 남의 집까지 올리면 사람이 늘수록 지도가 못 쓰게 된다.
// 예외는 `@home` 하나 — 내 집으로 돌아가는 지름길이다.
//
// **방 이름으로 잇는다.** `S_RoomList` 가 주는 것은 id·이름뿐이고 템플릿 id 는 안 온다.
// 이름은 `data/rooms/*.json` 의 `name` 과 한 글자도 다르면 안 된다.
// 짝이 없는 구역은 사라지지 않고 **"준비 중"** 으로 흐리게 남는다 — 앞으로 생길 곳을 미리 보여 주는 셈이다.

export interface LobbySpot {
  /** `data/rooms/*.json` 의 `name`. `"@home"` 이면 내 방(주인이 나인 방)을 찾는다. */
  room: string;
  label: string;
  /** 한 줄 설명. 마우스를 올리면 보인다. */
  hint: string;
  /** 배경 그림 위의 위치·크기 (%). */
  x: number; y: number; w: number; h: number;
}

/** 내 방을 가리키는 표식. 방 이름은 사람마다 달라서 고정 문자열로 못 적는다. */
export const HOME_SPOT = "@home";

